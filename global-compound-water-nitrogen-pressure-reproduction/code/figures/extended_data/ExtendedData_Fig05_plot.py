def regional_member_ranges(
    product,
    region_codes: np.ndarray,
    selected_codes: list[str],
) -> dict[str, dict[str, tuple[float, float]]]:
    area = np.asarray(product["basin_crop_area_ssp370_m2"], dtype=float)
    crop = np.isfinite(area) & (area > 0)
    cls_irr = np.asarray(product["QIRR_ssp370_member_class"], dtype=int)
    cls_noi = np.asarray(product["QNOI_ssp370_member_class"], dtype=int)

    if cls_irr.shape != cls_noi.shape:
        raise ValueError("IRR and NOI member-class arrays have different shapes.")

    output: dict[str, dict[str, tuple[float, float]]] = {}

    for code in selected_codes:
        region = region_codes == code
        retention_values: list[float] = []
        jaccard_values: list[float] = []

        for member in range(cls_irr.shape[0]):
            comp_irr = crop & region & (cls_irr[member] == 3)
            comp_noi = crop & region & (cls_noi[member] == 3)
            intersection = comp_irr & comp_noi
            union = comp_irr | comp_noi

            irr_area = float(np.sum(area[comp_irr]))
            union_area = float(np.sum(area[union]))
            intersection_area = float(np.sum(area[intersection]))

            retention_values.append(
                100.0 * intersection_area / irr_area if irr_area > 0 else np.nan
            )
            jaccard_values.append(
                100.0 * intersection_area / union_area if union_area > 0 else np.nan
            )

        retention_array = np.asarray(retention_values, dtype=float)
        retention_array = retention_array[np.isfinite(retention_array)]
        jaccard_array = np.asarray(jaccard_values, dtype=float)
        jaccard_array = jaccard_array[np.isfinite(jaccard_array)]

        output[code] = {
            "retention": (
                float(retention_array.min()) if retention_array.size else np.nan,
                float(retention_array.max()) if retention_array.size else np.nan,
            ),
            "jaccard": (
                float(jaccard_array.min()) if jaccard_array.size else np.nan,
                float(jaccard_array.max()) if jaccard_array.size else np.nan,
            ),
        }

    return output


def draw_panel_d(
    ax_retention: plt.Axes,
    ax_jaccard: plt.Axes,
    region_df: pd.DataFrame,
    overlap_df: pd.DataFrame,
    product,
    region_codes: np.ndarray,
) -> None:
    require_columns(
        region_df,
        [
            "period_key",
            "region_code",
            "QIRR_compound_area_million_km2",
            "retention_of_QIRR_compound_percent",
            "jaccard_percent",
        ],
        "regional summary",
    )
    require_columns(
        overlap_df,
        ["period_key", "retention_of_QIRR_compound_percent"],
        "overlap summary",
    )

    ssp3 = region_df[region_df["period_key"] == "ssp370"].copy()
    # Keep the scientific ranking: descending QIRR compound-cropland area.
    # Reverse only for plotting, so the largest region is shown at the top.
    ssp3 = (
        ssp3.sort_values("QIRR_compound_area_million_km2", ascending=False)
        .head(10)
        .iloc[::-1]
        .reset_index(drop=True)
    )

    y = np.arange(len(ssp3))
    retention = ssp3["retention_of_QIRR_compound_percent"].to_numpy(float)
    jaccard = ssp3["jaccard_percent"].to_numpy(float)
    selected_codes = ssp3["region_code"].astype(str).tolist()
    ranges = regional_member_ranges(product, region_codes, selected_codes)

    for ax, metric, values, color, marker, size in (
        (ax_retention, "retention", retention, RETENTION, "o", 29),
        (ax_jaccard, "jaccard", jaccard, JACCARD, "D", 27),
    ):
        for yy, code, value in zip(y, selected_codes, values):
            low, high = ranges[code][metric]
            low, high = finite_range(np.array([low, high]), value)
            ax.errorbar(
                value, yy,
                xerr=asymmetric_xerr(value, low, high),
                fmt="none", ecolor=color,
                elinewidth=0.65, capsize=1.45,
                capthick=0.65, alpha=0.76, zorder=2,
            )
        ax.scatter(
            values, y, s=size, marker=marker,
            facecolor=color, edgecolor="white",
            linewidth=0.45, zorder=3,
        )
        ax.set_ylim(-0.55, len(ssp3) - 0.05)
        ax.set_xlim(0, 102)
        ax.set_xticks([0, 50, 100])
        ax.grid(axis="x", color=GRID, lw=0.44)
        ax.set_axisbelow(True)
        format_stat_axis(ax)

    global_rows = overlap_df[overlap_df["period_key"] == "ssp370"]
    if global_rows.empty:
        raise ValueError("Missing SSP3-7.0 global retention value.")
    global_retention = float(
        global_rows.iloc[0]["retention_of_QIRR_compound_percent"]
    )

    ax_retention.axvline(
        global_retention,
        color=GLOBAL_LINE,
        lw=0.75,
        linestyle=(0, (3.0, 2.5)),
        alpha=1.0,
        zorder=0,
    )
    ax_retention.text(
        global_retention - 1.8,
        0.97,
        f"Global {global_retention:.0f}%",
        transform=ax_retention.get_xaxis_transform(),
        ha="right", va="top", fontsize=6.1,
        color="#737C81",
        clip_on=False,
        zorder=4,
    )

    ax_retention.set_yticks(y)
    ax_retention.set_yticklabels(selected_codes)
    ax_jaccard.set_yticks(y)
    ax_jaccard.set_yticklabels([])
    ax_jaccard.tick_params(axis="y", length=0)
    ax_retention.set_xlabel("Retention (%)", labelpad=4.0, fontsize=7.4)
    ax_jaccard.set_xlabel("Jaccard similarity (%)", labelpad=4.0, fontsize=7.4)


