def finite_range(values: np.ndarray, centre: float) -> tuple[float, float]:
    """Return a safe finite min-max range that always contains *centre*."""
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]
    if values.size == 0:
        return centre, centre
    return min(float(values.min()), centre), max(float(values.max()), centre)


def asymmetric_xerr(
    centre: float,
    low: float,
    high: float,
) -> np.ndarray:
    return np.array([[max(0.0, centre - low)], [max(0.0, high - centre)]])


def basin_to_grid(
    values: np.ndarray,
    code_grid: np.ndarray,
    lon: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    """Map one basin-level vector to the archived basin-code grid."""
    values = np.asarray(values, dtype=float)
    grid = np.full(code_grid.shape, np.nan, dtype=float)

    valid_grid = np.isfinite(code_grid) & (code_grid >= 0)
    rr, cc = np.where(valid_grid)
    idx = code_grid[rr, cc].astype(int)
    valid_idx = idx < values.size
    grid[rr[valid_idx], cc[valid_idx]] = values[idx[valid_idx]]

    lon180 = ((np.asarray(lon, dtype=float) + 180.0) % 360.0) - 180.0
    order = np.argsort(lon180)
    return lon180[order], grid[:, order]


def split_antimeridian(xs, ys):
    seg_x: list[float] = []
    seg_y: list[float] = []
    prev_x = None

    for x, y in zip(xs, ys):
        if prev_x is not None and abs(x - prev_x) > 180:
            if len(seg_x) > 1:
                yield seg_x, seg_y
            seg_x, seg_y = [], []
        seg_x.append(x)
        seg_y.append(y)
        prev_x = x

    if len(seg_x) > 1:
        yield seg_x, seg_y


def country_segments() -> list[np.ndarray]:
    """Read Natural Earth country outlines using pyshp when available."""
    try:
        import shapefile
    except ImportError:
        return []

    candidates = list(NE_ROOT.rglob("*.shp"))
    if not candidates:
        return []

    preferred = [
        path
        for path in candidates
        if "admin_0_countries" in path.name.lower()
    ]
    shp_path = preferred[0] if preferred else candidates[0]

    reader = shapefile.Reader(str(shp_path))
    segments: list[np.ndarray] = []
    for shape in reader.shapes():
        points = shape.points
        parts = list(shape.parts) + [len(points)]
        for start, end in zip(parts[:-1], parts[1:]):
            part = points[start:end]
            if len(part) < 2:
                continue
            xs = [((point[0] + 180.0) % 360.0) - 180.0 for point in part]
            ys = [point[1] for point in part]
            for sx, sy in split_antimeridian(xs, ys):
                segments.append(np.column_stack([sx, sy]))
    return segments


def format_map(ax: plt.Axes, segments: list[np.ndarray]) -> None:
    """Apply consistent map framing and light political boundaries."""
    ax.set_xlim(-180, 180)
    ax.set_ylim(-60, 85)
    ax.set_xticks([])
    ax.set_yticks([])
    ax.set_facecolor("white")

    for segment in segments:
        ax.plot(
            segment[:, 0],
            segment[:, 1],
            color=COAST,
            lw=0.24,
            alpha=0.78,
            zorder=20,
        )

    for spine in ax.spines.values():
        spine.set_visible(False)
    outline = getattr(ax, "outline_patch", None)
    if outline is not None:
        outline.set_visible(False)
    ax.patch.set_facecolor("white")
    ax.patch.set_edgecolor("none")


def figure_panel_heading(
    fig: plt.Figure,
    ax: plt.Axes,
    letter: str,
    title: str,
    context: str | None = None,
    anchor_left: float | None = None,
    anchor_right: float | None = None,
) -> None:
    """Place the panel heading independently of the plotting axes."""
    position = ax.get_position()
    left = position.x0 if anchor_left is None else anchor_left
    right = position.x1 if anchor_right is None else anchor_right
    y = position.y1 + 0.008
    fig.text(
        left,
        y,
        letter,
        ha="left",
        va="bottom",
        fontsize=10.0,
        fontweight="bold",
        color=TEXT,
        clip_on=False,
    )
    fig.text(
        left + 0.026,
        y,
        title,
        ha="left",
        va="bottom",
        fontsize=8.9,
        color=TEXT,
        clip_on=False,
    )
    if context:
        fig.text(
            right,
            y,
            context,
            ha="right",
            va="bottom",
            fontsize=6.9,
            color=MUTED,
            clip_on=False,
        )


def align_left_ticklabels_to_figure_x(
    ax: plt.Axes,
    figure_x: float,
) -> None:
    """Left-align y tick labels at a shared figure-coordinate anchor."""
    position = ax.get_position()
    axes_x = (figure_x - position.x0) / position.width
    for label in ax.get_yticklabels():
        label.set_horizontalalignment("left")
        label.set_x(axes_x)


