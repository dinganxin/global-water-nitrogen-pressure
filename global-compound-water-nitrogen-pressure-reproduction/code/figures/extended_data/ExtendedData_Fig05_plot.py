def embed_editable_svg_fonts(path: Path) -> None:
    """Embed regular and bold DejaVu Sans while retaining SVG text nodes."""
    svg_ns = "http://www.w3.org/2000/svg"
    xlink_ns = "http://www.w3.org/1999/xlink"
    ET.register_namespace("", svg_ns)
    ET.register_namespace("xlink", xlink_ns)

    regular_path = Path(
        font_manager.findfont(
            font_manager.FontProperties(family="DejaVu Sans")
        )
    )
    bold_path = Path(
        font_manager.findfont(
            font_manager.FontProperties(
                family="DejaVu Sans",
                weight="bold",
            )
        )
    )
    regular = base64.b64encode(regular_path.read_bytes()).decode("ascii")
    bold = base64.b64encode(bold_path.read_bytes()).decode("ascii")

    tree = ET.parse(path)
    root = tree.getroot()
    defs = root.find(f"{{{svg_ns}}}defs")
    if defs is None:
        defs = ET.Element(f"{{{svg_ns}}}defs")
        root.insert(0, defs)

    style = ET.SubElement(
        defs,
        f"{{{svg_ns}}}style",
        {"type": "text/css"},
    )
    style.text = (
        "\n@font-face {"
        "font-family:'EmbeddedDejaVuSans';"
        f"src:url(data:font/ttf;base64,{regular}) format('truetype');"
        "font-weight:400;font-style:normal;}\n"
        "@font-face {"
        "font-family:'EmbeddedDejaVuSans';"
        f"src:url(data:font/ttf;base64,{bold}) format('truetype');"
        "font-weight:700;font-style:normal;}\n"
        "text {font-family:'EmbeddedDejaVuSans' !important;}\n"
    )
    tree.write(path, encoding="utf-8", xml_declaration=True)


