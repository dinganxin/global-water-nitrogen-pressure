def plot(root: Path, map_cache_path: Path, output_dir: Path) -> Path:
    set_style()
    product, tables, region_codes = load_inputs(root)
    map_cache = load_map_cache(map_cache_path)
    segments = country_segments()

    # A slightly flatter canvas and nested top-row slots produce a much tighter
    # editorial layout than manually separated axes.
    fig = plt.figure(figsize=(7.50, 4.85), facecolor="white")
    outer = fig.add_gridspec(
        2,
        2,
        left=0.070,
        right=0.985,
        bottom=0.105,
        top=0.945,
        width_ratios=[1.00, 1.00],
        height_ratios=[0.90, 1.05],
        wspace=0.125,
        hspace=0.155,
    )

    top_a = outer[0, 0].subgridspec(
        2,
        1,
        height_ratios=[1.00, 0.18],
        hspace=0.0,
    )
    top_b = outer[0, 1].subgridspec(
        2,
        1,
        height_ratios=[1.00, 0.18],
        hspace=0.0,
    )

    ax_a = fig.add_subplot(top_a[0, 0])
    cbar_slot = fig.add_subplot(top_a[1, 0])
    cbar_slot.axis("off")

    ax_b = fig.add_subplot(top_b[0, 0])
    legend_b = fig.add_subplot(top_b[1, 0])

    ax_c = fig.add_subplot(outer[1, 0])
    ax_d = fig.add_subplot(outer[1, 1])

    # Preserve equal top-map dimensions while allocating the lower row at
    # approximately 0.95:1.05 (panel c:panel d).
    pos_c = ax_c.get_position()
    pos_d = ax_d.get_position()
    base_width = pos_c.width
    ax_c.set_position(
        [pos_c.x0, pos_c.y0, 0.95 * base_width, pos_c.height]
    )
    ax_d.set_position(
        [
            pos_d.x0 - 0.05 * base_width,
            pos_d.y0,
            1.05 * base_width,
            pos_d.height,
        ]
    )

    # Shift and contract the lower plotting rectangles independently of their
    # headings, leaving aligned gutters for the categorical y-axis labels.
    pos_c = ax_c.get_position()
    pos_d = ax_d.get_position()
    lower_height_scale = 0.88
    lower_downward_extension = 0.024
    ax_c.set_position(
        [
            pos_c.x0 + 0.058,
            pos_c.y0 - lower_downward_extension,
            pos_c.width - 0.070,
            pos_c.height * lower_height_scale + lower_downward_extension,
        ]
    )
    ax_d.set_position(
        [
            pos_d.x0 + 0.052,
            pos_d.y0 - lower_downward_extension,
            pos_d.width - 0.064,
            pos_d.height * lower_height_scale + lower_downward_extension,
        ]
    )
    d_position = ax_d.get_position()
    d_gap = 0.019
    d_width = (d_position.width - d_gap) / 2.0
    ax_d.set_position(
        [d_position.x0, d_position.y0, d_width, d_position.height]
    )
    ax_d_jaccard = fig.add_axes(
        [
            d_position.x0 + d_width + d_gap,
            d_position.y0,
            d_width,
            d_position.height,
        ]
    )

    # Match the colourbar span to the panel-a map frame.
    slot = cbar_slot.get_position()
    cax_a = fig.add_axes(
        [
            slot.x0,
            slot.y0 + 0.58 * slot.height,
            slot.width,
            0.252 * slot.height,
        ]
    )

    draw_panel_a(fig, ax_a, cax_a, product, map_cache, segments)
    draw_panel_b(ax_b, legend_b, product, map_cache, segments)
    draw_panel_c(ax_c, tables["global"], tables["member"])
    draw_panel_d(
        ax_d,
        ax_d_jaccard,
        tables["region"],
        tables["overlap"],
        product,
        region_codes,
    )

    map_a_position = ax_a.get_position()
    map_b_position = ax_b.get_position()
    align_left_ticklabels_to_figure_x(ax_c, map_a_position.x0 + 0.005)
    align_left_ticklabels_to_figure_x(ax_d, map_b_position.x0 - 0.010)

    figure_panel_heading(
        fig,
        ax_a,
        "a",
        "Runoff difference between IRR and NOI",
    )
    figure_panel_heading(
        fig,
        ax_b,
        "b",
        "Compound hotspot agreement",
    )
    figure_panel_heading(
        fig,
        ax_c,
        "c",
        "Global cropland area by runoff denominator",
        anchor_left=map_a_position.x0,
    )
    figure_panel_heading(
        fig,
        ax_d,
        "d",
        "Regional hotspot agreement",
        anchor_left=map_b_position.x0,
    )

    output = (
        output_dir
        / "ExtendedData_Fig05_runoff_denominator_sensitivity"
    )
    output.parent.mkdir(parents=True, exist_ok=True)

    save_common = {
        "facecolor": "white",
        "edgecolor": "none",
        "bbox_inches": "tight",
        "pad_inches": 0.08,
        "metadata": {"Creator": "Matplotlib"},
    }
    fig.savefig(output.with_suffix(".png"), dpi=600, **save_common)
    fig.savefig(output.with_suffix(".pdf"), **save_common)
    fig.savefig(output.with_suffix(".svg"), **save_common)
    embed_editable_svg_fonts(output.with_suffix(".svg"))

    plt.close(fig)
    return output.with_suffix(".png")


def main() -> None:
    args = parse_args()
    output = plot(args.root, args.map_cache, args.output_dir)
    print(output)


