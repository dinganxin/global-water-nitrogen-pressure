def load_inputs(root: Path):
    data_file = (
        root
        / "data"
        / "extended_data"
        / "runoff_denominator_sensitivity_strict_positiveQ_01pct.npz"
    )
    table_dir = root / "tables" / "extended_data" / "ExtendedData_Fig05"

    require_path(data_file, "NPZ product")
    meta_path = (
        root
        / "data"
        / "basin_metadata"
        / "HydroBASINS_level5_metadata_and_IPCC_assignment.csv"
    )
    require_path(meta_path, "basin metadata table")

    table_paths = {
        "global": table_dir / "hydrological_denominator_global_summary.csv",
        "overlap": table_dir / "hydrological_denominator_compound_overlap_summary.csv",
        "region": table_dir / "hydrological_denominator_IPCC_AR6_summary.csv",
        "member": table_dir / "hydrological_denominator_member_summary.csv",
    }
    for name, path in table_paths.items():
        require_path(path, f"{name} table")

    product = np.load(data_file, allow_pickle=False)
    tables = {name: pd.read_csv(path) for name, path in table_paths.items()}

    raw_meta = pd.read_csv(
        meta_path,
        usecols=["HYBAS_ID", "dominant_ipcc_region_code"],
    ).drop_duplicates("HYBAS_ID")

    meta = pd.DataFrame(
        {"HYBAS_ID": np.asarray(product["basin_ids"], dtype=np.int64)}
    ).merge(raw_meta, on="HYBAS_ID", how="left")

    region_codes = (
        meta["dominant_ipcc_region_code"]
        .fillna("NA")
        .astype(str)
        .to_numpy()
    )

    return product, tables, region_codes


def load_map_cache(path: Path) -> dict[str, np.ndarray]:
    require_path(path, "HydroBASINS display-raster cache")
    cache = np.load(path, allow_pickle=False)
    required = {
        "delta_qirr_minus_qnoi_mm_yr",
        "hotspot_status",
        "extent",
    }
    missing = required.difference(cache.files)
    if missing:
        raise KeyError(f"Map cache is missing keys: {sorted(missing)}")
    delta = np.asarray(cache["delta_qirr_minus_qnoi_mm_yr"], dtype=float)
    status = np.asarray(cache["hotspot_status"], dtype=int)
    if delta.shape != status.shape:
        raise AssertionError("Panel-a and panel-b display rasters differ in shape.")
    return {
        "delta": delta,
        "status": status,
        "extent": np.asarray(cache["extent"], dtype=float),
    }


# -----------------------------------------------------------------------------
# Panel a
# -----------------------------------------------------------------------------
def draw_panel_a(
    fig: plt.Figure,
    ax: plt.Axes,
    cax: plt.Axes,
    product,
    map_cache: dict[str, np.ndarray],
    segments: list[np.ndarray],
) -> None:
    # Independently verify that the display cache preserves the audited
    # basin-value range before drawing it.
    delta = (
        np.asarray(product["QIRR_ssp370_q_depth_mm_yr"], dtype=float)
        - np.asarray(product["QNOI_ssp370_q_depth_mm_yr"], dtype=float)
    )
    delta_grid = np.asarray(map_cache["delta"], dtype=float)
    finite_grid = delta_grid[np.isfinite(delta_grid)]
    if finite_grid.size == 0:
        raise ValueError("Panel-a HydroBASINS display raster is empty.")
    if finite_grid.min() < np.nanmin(delta) - 1e-5:
        raise AssertionError("Panel-a raster contains values below basin data.")
    if finite_grid.max() > np.nanmax(delta) + 1e-5:
        raise AssertionError("Panel-a raster contains values above basin data.")

    cmap = ListedColormap(RUNOFF_COLORS)
    cmap.set_under("#54206A")
    cmap.set_over("#0D5F2A")
    norm = BoundaryNorm(RUNOFF_BOUNDS, cmap.N)

    mesh = ax.imshow(
        delta_grid,
        extent=tuple(map_cache["extent"]),
        origin="upper",
        cmap=cmap,
        norm=norm,
        interpolation="nearest",
        aspect="auto",
        rasterized=True,
        zorder=1,
    )

    format_map(ax, segments)

    cbar = fig.colorbar(
        mesh,
        cax=cax,
        orientation="horizontal",
        extend="both",
        extendfrac=0.060,
        ticks=RUNOFF_TICKS,
    )
    cbar.outline.set_linewidth(0.40)
    cbar.outline.set_edgecolor(AXIS)
    cbar.ax.minorticks_off()
    cbar.ax.xaxis.set_minor_locator(mpl.ticker.NullLocator())
    cbar.ax.set_xticklabels(["-300", "-100", "-50", "0", "50", "100", "300"])
    cbar.ax.tick_params(
        length=2.2,
        width=0.45,
        pad=1.0,
        labelsize=7.0,
        color=AXIS,
    )
    cbar.set_label(
        r"$Q_{\mathrm{IRR}}$-$Q_{\mathrm{NOI}}$ runoff depth (mm yr⁻¹)",
        labelpad=1.7,
        fontsize=8.1,
        fontfamily="DejaVu Sans",
        color=TEXT,
    )


