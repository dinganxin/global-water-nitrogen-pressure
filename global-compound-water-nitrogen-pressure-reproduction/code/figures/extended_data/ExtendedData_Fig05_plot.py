def draw_panel_c(
    ax: plt.Axes,
    global_df: pd.DataFrame,
    member_df: pd.DataFrame,
) -> None:
    required_global = [
        "period_key",
        "denominator",
        "compound_area_million_km2",
        "nonpositive_Q_area_million_km2",
    ]
    required_member = required_global
    require_columns(global_df, required_global, "global summary")
    require_columns(member_df, required_member, "member summary")

    metric_specs = (
        ("Compound cropland", "compound_area_million_km2", 6.0),
        (r"Cropland with $Q\leq0$", "nonpositive_Q_area_million_km2", 2.0),
    )
    tick_positions: list[float] = []
    tick_labels: list[str] = []

    for heading, column, first_y in metric_specs:
        ax.text(
            0.04, first_y + 0.78, heading,
            transform=ax.get_yaxis_transform(),
            ha="left", va="center", fontsize=7.0,
            fontweight="bold", color=TEXT,
        )
        for index, period in enumerate(PERIODS):
            yy = first_y - index
            tick_positions.append(yy)
            tick_labels.append(PERIOD_LABELS[period])
            irr_rows = global_df[
                (global_df["period_key"] == period)
                & (global_df["denominator"] == "QIRR")
            ]
            noi_rows = global_df[
                (global_df["period_key"] == period)
                & (global_df["denominator"] == "QNOI")
            ]
            if irr_rows.empty or noi_rows.empty:
                raise ValueError(
                    f"Missing global summary row for {period}, column {column}."
                )

            v_irr = float(irr_rows.iloc[0][column])
            v_noi = float(noi_rows.iloc[0][column])
            ax.plot(
                [v_irr, v_noi],
                [yy, yy],
                color=CONNECTOR,
                lw=1.05,
                solid_capstyle="round",
                zorder=1,
            )

            for denominator, value, color in (
                ("QIRR", v_irr, QIRR),
                ("QNOI", v_noi, QNOI),
            ):
                member_values = member_df[
                    (member_df["period_key"] == period)
                    & (member_df["denominator"] == denominator)
                ][column].to_numpy(float)
                low, high = finite_range(member_values, value)
                ax.errorbar(
                    value,
                    yy,
                    xerr=asymmetric_xerr(value, low, high),
                    fmt="none",
                    ecolor=color,
                    elinewidth=0.62,
                    capsize=1.4,
                    capthick=0.62,
                    alpha=0.72,
                    zorder=2,
                )
                ax.scatter(
                    value,
                    yy,
                    s=30,
                    marker="o",
                    facecolor=color,
                    edgecolor="white",
                    linewidth=0.45,
                    zorder=3,
                )

    ax.set_xlim(0.0, 3.0)
    ax.set_xticks([0, 1, 2, 3])

    ax.set_yticks(tick_positions)
    ax.set_yticklabels(tick_labels)
    ax.set_ylim(-0.55, 7.25)
    ax.set_xlabel(
        "Cropland area (million km²)",
        labelpad=4.0,
        fontsize=8.1,
    )
    ax.grid(axis="x", color=GRID, lw=0.48, alpha=1.0)
    ax.set_axisbelow(True)

    denominator_handles = [
        Line2D(
            [0],
            [0],
            marker="o",
            linestyle="none",
            markerfacecolor=QIRR,
            markeredgecolor="white",
            markersize=4.8,
            label="IRR runoff",
        ),
        Line2D(
            [0],
            [0],
            marker="o",
            linestyle="none",
            markerfacecolor=QNOI,
            markeredgecolor="white",
            markersize=4.8,
            label="NOI runoff",
        ),
    ]

    ax.legend(
        handles=denominator_handles,
        loc="upper left",
        bbox_to_anchor=(2.18, 6.26),
        bbox_transform=ax.transData,
        ncol=1,
        fontsize=6.4,
        handlelength=0.65,
        handletextpad=0.35,
        labelspacing=0.42,
        borderaxespad=0.0,
    )

    format_stat_axis(ax)


