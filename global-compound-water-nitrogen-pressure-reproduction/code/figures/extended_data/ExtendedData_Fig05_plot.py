def draw_panel_b(
    ax: plt.Axes,
    legend_ax: plt.Axes,
    product,
    map_cache: dict[str, np.ndarray],
    segments: list[np.ndarray],
) -> None:
    qirr_pos = np.asarray(product["QIRR_ssp370_q_positive"], dtype=bool)
    qnoi_pos = np.asarray(product["QNOI_ssp370_q_positive"], dtype=bool)
    comp_irr = np.asarray(product["QIRR_ssp370_class"], dtype=int) == 3
    comp_noi = np.asarray(product["QNOI_ssp370_class"], dtype=int) == 3
    common_positive = qirr_pos & qnoi_pos

    status = np.full(comp_irr.shape, np.nan, dtype=float)
    future_crop = (
        np.asarray(product["basin_crop_area_ssp370_m2"], dtype=float) > 0
    )
    status[future_crop & common_positive & ~comp_irr & ~comp_noi] = 0
    status[future_crop & common_positive & comp_irr & comp_noi] = 1
    status[future_crop & common_positive & comp_irr & ~comp_noi] = 2
    status[future_crop & common_positive & ~comp_irr & comp_noi] = 3
    status[future_crop & ~common_positive] = 4
    expected_codes = set(np.unique(status[np.isfinite(status)]).astype(int))
    if expected_codes != {0, 1, 2, 3, 4}:
        raise AssertionError(f"Unexpected basin status codes: {expected_codes}")

    status_grid = np.asarray(map_cache["status"], dtype=int)
    raster_codes = set(np.unique(status_grid[status_grid >= 0]).astype(int))
    if raster_codes != expected_codes:
        raise AssertionError(
            f"Map-cache status codes {raster_codes} do not match {expected_codes}."
        )
    status_masked = np.ma.masked_where(status_grid < 0, status_grid)
    cmap = ListedColormap(
        [
            NEITHER,
            PANEL_B_SHARED,
            PANEL_B_QIRR_ONLY,
            PANEL_B_QNOI_ONLY,
            OUTSIDE_COMMON_Q,
        ]
    )
    norm = BoundaryNorm([-0.5, 0.5, 1.5, 2.5, 3.5, 4.5], cmap.N)

    ax.imshow(
        status_masked,
        extent=tuple(map_cache["extent"]),
        origin="upper",
        cmap=cmap,
        norm=norm,
        interpolation="nearest",
        aspect="auto",
        rasterized=True,
        zorder=1,
    )

    # Match the main Fig. 3 texture: retain the complete light-grey outside-
    # domain fill and add approximately one restrained point per native model
    # grid cell (about 0.9 degrees by 1.2 degrees). Sampling changes only the
    # texture density, never the mask area.
    outside_mask = status_grid == 4
    n_rows, n_cols = outside_mask.shape
    row_stride = 9
    col_stride = 12
    row_index = np.arange(row_stride // 2, n_rows, row_stride)
    col_index = np.arange(col_stride // 2, n_cols, col_stride)
    sampled = outside_mask[np.ix_(row_index, col_index)]
    sample_row, sample_col = np.where(sampled)
    xmin, xmax, ymin, ymax = map_cache["extent"]
    dot_x = xmin + (col_index + 0.5) * (xmax - xmin) / n_cols
    dot_y = ymax - (row_index + 0.5) * (ymax - ymin) / n_rows
    ax.scatter(
        dot_x[sample_col],
        dot_y[sample_row],
        s=0.82,
        marker=".",
        color=OUTSIDE_COMMON_Q_DOT,
        alpha=0.70,
        linewidths=0,
        rasterized=True,
        zorder=3,
    )

    format_map(ax, segments)

    handles = [
        Patch(
            facecolor=PANEL_B_SHARED,
            edgecolor="none",
            label="Shared",
        ),
        Patch(
            facecolor=PANEL_B_QIRR_ONLY,
            edgecolor="none",
            label=r"$Q_{\mathrm{IRR}}$ only",
        ),
        Patch(
            facecolor=PANEL_B_QNOI_ONLY,
            edgecolor="none",
            label=r"$Q_{\mathrm{NOI}}$ only",
        ),
        Patch(
            facecolor=NEITHER,
            edgecolor="none",
            label="Neither",
        ),
        OutsideDomainLegendHandle("Outside common domain"),
    ]
    legend_ax.axis("off")
    # Fixed columns reproduce the reference layout without allowing the long
    # outside-domain label to push the QNOI entry away from QIRR.
    column_x = [0.20, 0.45, 0.70]
    row_y = [0.70, 0.10]
    marker_size = 42.0
    text_dx = 0.027

    def legend_entry(x, y, label, facecolor, edgecolor="none"):
        legend_ax.scatter(
            [x],
            [y],
            marker="s",
            s=marker_size,
            facecolor=facecolor,
            edgecolor=edgecolor,
            linewidth=0.45,
            transform=legend_ax.transAxes,
            clip_on=False,
            zorder=2,
        )
        legend_ax.text(
            x + text_dx,
            y,
            label,
            transform=legend_ax.transAxes,
            ha="left",
            va="center",
            fontsize=7.4,
            color=TEXT,
        )

    legend_entry(column_x[0], row_y[0], "Shared", PANEL_B_SHARED)
    legend_entry(column_x[1], row_y[0], r"$Q_{\mathrm{IRR}}$ only", PANEL_B_QIRR_ONLY)
    legend_entry(column_x[2], row_y[0], r"$Q_{\mathrm{NOI}}$ only", PANEL_B_QNOI_ONLY)
    legend_entry(column_x[0], row_y[1], "Neither", NEITHER)
