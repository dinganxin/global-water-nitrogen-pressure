class HandlerOutsideDomain(HandlerBase):
    """Draw the same light fill and dot texture used on the map."""

    def create_artists(
        self,
        legend,
        orig_handle,
        xdescent,
        ydescent,
        width,
        height,
        fontsize,
        trans,
    ):
        rectangle = Rectangle(
            (xdescent, ydescent),
            width,
            height,
            facecolor=OUTSIDE_COMMON_Q,
            edgecolor=OUTSIDE_COMMON_Q_EDGE,
            linewidth=0.40,
            transform=trans,
        )
        dot = Line2D(
            [xdescent + width / 2.0],
            [ydescent + height / 2.0],
            marker="o",
            markersize=1.0,
            markerfacecolor=OUTSIDE_COMMON_Q_DOT,
            markeredgecolor=OUTSIDE_COMMON_Q_DOT,
            markeredgewidth=0,
            alpha=0.72,
            linestyle="none",
            transform=trans,
        )
        return [rectangle, dot]


